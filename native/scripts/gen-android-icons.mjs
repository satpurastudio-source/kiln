// Turns src/components/Icons.jsx into plain path data for the Android app, so both
// keep the same icons. Run from the repo root: node native/scripts/gen-android-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs'
const src = readFileSync('src/components/Icons.jsx', 'utf8')
const attr = (s, k) => s.match(new RegExp(`\\b${k}="([^"]*)"`))?.[1]
const out = {}
for (const part of src.split(/export const /).slice(1)) {
  const name = part.match(/^(\w+)Icon/)?.[1]
  if (!name) continue
  const d = []
  for (const line of part.split('\n')) {
    if (line.includes('filled &&')) continue
    for (const m of line.matchAll(/<(path|circle|rect|line|polyline|polygon)\b[^>]*>/g)) {
      const e = m[0]
      if (m[1] === 'path') d.push(attr(e, 'd'))
      if (m[1] === 'line') d.push(`M${attr(e, 'x1')} ${attr(e, 'y1')}L${attr(e, 'x2')} ${attr(e, 'y2')}`)
      if (m[1] === 'polyline' || m[1] === 'polygon') d.push('M' + attr(e, 'points').trim().split(/\s+/).join('L') + (m[1] === 'polygon' ? 'z' : ''))
      if (m[1] === 'circle') {
        const [x, y] = [+attr(e, 'cx'), +attr(e, 'cy')]
        const r = +(attr(e, 'r') ?? e.match(/\? '([\d.]+)' : '([\d.]+)'/)?.[2])
        d.push(`M${x - r} ${y}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`)
      }
      if (m[1] === 'rect') {
        const [x, y, w, h, r] = ['x', 'y', 'width', 'height', 'rx'].map((k) => +(attr(e, k) ?? 0))
        d.push(`M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}z`)
      }
    }
  }
  if (d.length) out[name] = d.join(' ')
}
const body = Object.entries(out).map(([k, v]) => `    "${k}" to "${v}",`).join('\n')
writeFileSync('native/android/app/src/main/java/com/satpurastudio/kiln/ui/IconData.kt',
`package com.satpurastudio.kiln.ui

// Generated by native/scripts/gen-android-icons.mjs from src/components/Icons.jsx.
val ICON_PATHS = mapOf(
${body}
)
`)
console.log(Object.keys(out).join(' '))
